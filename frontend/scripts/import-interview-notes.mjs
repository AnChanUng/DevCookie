import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = fs.readFileSync(new URL('src/data/vendor/backend-interview-question.md', root), 'utf8');
export const REVISION = '71f0300c379837e2f5666bbe19630a3d3fbc2bb2';
const repo = 'https://github.com/ksundong/backend-interview-question';
const excluded = new Set(['커뮤니케이션', '기타', '개인의 역량', '최신기술에 관심이 있는지']);
const sections = [];
let active = false, section = null, blocked = false;
const decode = text => text.replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n)).replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/<[^>]*>/g, '').trim();
// Details blocks are captured as one token so headings within an answer cannot
// accidentally change the surrounding subject. The pinned source has no nested details.
const tokens = /^(#{2,4}) (.+)$|<details\b[^>]*>[\s\S]*?<\/details>/gm;
for (const match of source.matchAll(tokens)) {
  if (match[1]) {
    const level = match[1].length, title = match[2].trim();
    if (level === 2) { active = ['CS 관련 지식', '언어 관련', '기타'].includes(title); section = null; blocked = false; }
    if ((level === 3 || level === 4) && active) {
      blocked = excluded.has(title);
      section = { id: 'source-' + createHash('sha256').update(title).digest('hex').slice(0, 12), title, items: [] };
      if (!blocked) sections.push(section);
    }
    continue;
  }
  if (!active || !section || blocked) continue;
  const summary = /<summary[^>]*>([\s\S]*?)<\/summary>/.exec(match[0]);
  if (!summary) throw new Error('Question missing summary');
  const question = decode(summary[1]);
  if (!question) continue;
  const answerMarkdown = match[0].slice(summary.index + summary[0].length).replace(/<\/details>\s*$/, '').trim();
  const hasAnswer = !!decode(answerMarkdown).trim();
  const line = source.slice(0, match.index).split('\n').length;
  section.items.push({
    id: 'ksundong-' + createHash('sha256').update(section.title + '\n' + question).digest('hex').slice(0, 16),
    title: question, question,
    answer: hasAnswer ? decode(answerMarkdown) : '원문에 답변이 작성되어 있지 않습니다.',
    answerMarkdown: hasAnswer ? answerMarkdown : '',
    sourceUrl: `${repo}/blob/${REVISION}/README.md#L${line}`,
  });
}
const notes = sections.filter(s => s.items.length);
fs.writeFileSync(fileURLToPath(new URL('src/data/interviewNotes.js', root)), '// Generated by scripts/import-interview-notes.mjs. Original wording preserved.\nexport const INTERVIEW_NOTES = ' + JSON.stringify(notes, null, 2) + ';\n');
console.log(notes.map(s => `${s.title}: ${s.items.length}`).join('\n'));
console.log('Imported', notes.reduce((n,s)=>n+s.items.length,0), 'questions');
