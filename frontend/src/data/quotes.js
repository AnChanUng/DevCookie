const DAY_MS = 24 * 60 * 60 * 1000;
// 순환 시작일(2026-11-18의 한국 날짜 번호). 이날 첫 번째 문장이 나오고 다음 날부터 차례로 돌아간다
const START_DAY = 20775;

// 한국 날짜 번호(0시 기준)로 그날의 명언을 고른다
export function quoteForDay(day = Math.floor((Date.now() + 9 * 60 * 60 * 1000) / DAY_MS)) {
  const n = QUOTES.length;
  return QUOTES[(((day - START_DAY) % n) + n) % n];
}
