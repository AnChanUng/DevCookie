export function coreParts(text, id) {
  const phrases = [...(ANSWER_CORES[id] || [])].sort((a,b) => b.length-a.length);
  const parts = [];
  let at = 0;
  while (at < text.length) {
    let start = text.length, match = '';
    for (const phrase of phrases) {
      const index = text.indexOf(phrase, at);
      if (index >= 0 && index < start) { start = index; match = phrase; }
    }
    if (start > at) parts.push({ text: text.slice(at, start), bold: false });
    if (!match) break;
    parts.push({ text: match, bold: true });
    at = start + match.length;
  }
  return parts;
}
export function coreMarkdown(text, id) {
  return coreParts(text, id).map(part => part.bold ? '**' + part.text + '**' : part.text).join('');
}
