export function theoryFor(q) {
  const topic = q?.topic;
  if (!topic) return null;
  const hit = RULES.find(([re, , , not]) => re.test(topic) && !not?.test(topic));
  return hit ? { id: hit[1], title: hit[2] } : null;
}
